#!/usr/bin/env python3
"""Generate the fixture PCF and ESP channel table from the carrier LED map.

Inputs:
  docs/led-map.json                                  carrier monitor channels
  ../esp32-fpga-module/fab/checks/module-netlist.xml module v1 connector/package pins

Outputs:
  firmware/fpga/project.pcf
  firmware/firmware/main/carrier_map.h

Run from anywhere: python3 boards/programming-carrier/firmware/tools/gen_pinmap.py
"""
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent
CARRIER = PROJECT.parent
LED_MAP = CARRIER / "docs/led-map.json"
NETLIST = CARRIER.parent / "esp32-fpga-module/fab/checks/module-netlist.xml"

# FPGA pins used by the module-internal ESP32 link (LINK_* nets).
FPGA_SPI = {"SPI_SO": "LINK_MISO", "SPI_SCK": "LINK_SCK", "SPI_SS_N": "LINK_CS_N", "SPI_SI": "LINK_MOSI"}

# README "Pin classes": what the firmware may do with each ESP signal.
ESP_CLASS = {
    "ESP_EN": "CH_OBSERVE",          # chip enable; SW2 reset tests it
    "ESP_GPIO0_BOOT": "CH_OBSERVE",  # boot strap; SW1 controls it
    "ESP_GPIO45": "CH_OPT_IN",       # flash-voltage strap; separate opt-in test
    "ESP_GPIO46": "CH_INPUT",        # input only; SW3 button
}


def load_nets():
    root = ET.parse(NETLIST).getroot()
    nets = {}
    for net in root.iter("net"):
        name = net.get("name").lstrip("/")
        nets[name] = {n.get("ref"): n.get("pin") for n in net.iter("node")}
    return nets


def main():
    leds = json.loads(LED_MAP.read_text())
    nets = load_nets()

    channels = []
    fpga_bit = 0
    for e in leds:
        sig = e["signal"]
        nodes = nets[sig]
        conn = "J1" if "J1" in nodes else "J2"
        ch = {
            "signal": sig,
            "led": e["led"],
            "buffer": e["buffer"],
            "bank": e["bank"],
            "active_low": e["active_low"],
            "conn": conn,
            "conn_pin": int(nodes[conn]),
        }
        if e["bank"] == "ESP":
            ch["pkg_pin"] = int(nodes["U1"])
            m = re.match(r"ESP_GPIO(\d+)", sig)
            ch["gpio"] = int(m.group(1)) if m else -1
            ch["cls"] = ESP_CLASS.get(sig, "CH_OUTPUT")
            ch["index"] = ch["gpio"]
        elif e["bank"] == "FPGA":
            ch["pkg_pin"] = int(nodes["U2"])
            ch["cls"] = "CH_OUTPUT"
            ch["index"] = fpga_bit
            fpga_bit += 1
        else:
            ch["pkg_pin"] = int(nodes["U2"])
            ch["cls"] = "CH_RGB"
            ch["index"] = int(sig[-1])
        channels.append(ch)

    assert fpga_bit == 30, fpga_bit

    # ---- PCF ----
    pcf = [
        "# GENERATED by tools/gen_pinmap.py from docs/led-map.json and the module v1 netlist.",
        "# Do not edit by hand.",
        "",
        "# Module-internal ESP32-S2 link (FPGA SPI configuration pins, reused at runtime)",
    ]
    for port, net in FPGA_SPI.items():
        pcf.append(f"set_io {port:<10} {nets[net]['U2']}")
    pcf += ["", "# Carrier monitor outputs: fpga_out[n] -> LED, bit order = led-map.json order"]
    for ch in channels:
        if ch["bank"] == "FPGA":
            port = f"fpga_out[{ch['index']}]"
            pcf.append(f"set_io {port:<12} {ch['pkg_pin']:>2}  # {ch['led']} {ch['buffer']} {ch['signal']} {ch['conn']}-{ch['conn_pin']}")
    pcf += ["", "# RGB current sinks (SB_RGBA_DRV), shared with module D1 and carrier red monitors"]
    for ch in channels:
        if ch["bank"] == "RGB":
            pcf.append(f"set_io RGB{ch['index']:<7} {ch['pkg_pin']}  # {ch['led']} {ch['signal']} {ch['conn']}-{ch['conn_pin']}")
    (PROJECT / "fpga/project.pcf").write_text("\n".join(pcf) + "\n")

    # ---- C header ----
    banks = []
    for ch in channels:
        if ch["buffer"] not in banks:
            banks.append(ch["buffer"])
    h = [
        "// GENERATED by tools/gen_pinmap.py from docs/led-map.json and the module v1 netlist.",
        "// Do not edit by hand.",
        "#pragma once",
        "",
        "#include \"carrier_types.h\"",
        "",
        f"#define CARRIER_CHANNEL_COUNT {len(channels)}",
        f"#define CARRIER_BANK_COUNT {len(banks)}",
        "",
        "// Physical order: grouped by buffer, input-pin order within each buffer.",
        "static const carrier_channel_t CARRIER_CHANNELS[CARRIER_CHANNEL_COUNT] = {",
    ]
    for ch in channels:
        kind = {"ESP": "KIND_ESP", "FPGA": "KIND_FPGA", "RGB": "KIND_RGB"}[ch["bank"]]
        h.append(
            f'    {{ "{ch["signal"]}", "{ch["led"]}", "{ch["buffer"]}", {kind}, {ch["cls"]}, '
            f'{ch["index"]}, "{ch["conn"]}", {ch["conn_pin"]}, {ch["pkg_pin"]}, {str(ch["active_low"]).lower()} }},'
        )
    h += ["};", "", "static const char *const CARRIER_BANKS[CARRIER_BANK_COUNT] = {"]
    h += [f'    "{b}",' for b in banks]
    h += ["};", ""]
    (PROJECT / "firmware/main/carrier_map.h").write_text("\n".join(h))


if __name__ == "__main__":
    main()
